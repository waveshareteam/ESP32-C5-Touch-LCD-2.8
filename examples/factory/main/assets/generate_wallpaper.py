"""Generate the 320x480 desktop wallpaper as an LVGL 9 RGB565 asset (Pillow)."""
from pathlib import Path
from PIL import Image, ImageOps
import struct

ROOT = Path(__file__).resolve().parent
image = Image.open(ROOT / "desktop_wallpaper_source.png").convert("RGB")
image = ImageOps.fit(image, (320, 480), method=Image.Resampling.LANCZOS)
pixels = bytearray()
for red, green, blue in image.getdata():
    pixels.extend(struct.pack("<H", ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)))
lines = ['/* Generated by generate_wallpaper.py. */', '#include "lvgl.h"', '',
         'static const LV_ATTRIBUTE_MEM_ALIGN uint8_t wallpaper_pixels[] = {']
for offset in range(0, len(pixels), 32):
    lines.append("    " + ",".join(f"0x{value:02x}" for value in pixels[offset:offset + 32]) + ",")
lines += ['};', '', 'const lv_image_dsc_t img_desktop_wallpaper = {',
          '    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,',
          '                .w = 320, .h = 480, .stride = 320 * 2 },',
          '    .data_size = sizeof(wallpaper_pixels), .data = wallpaper_pixels,',
          '};', '']
(ROOT / "img_desktop_wallpaper.c").write_text("\n".join(lines), encoding="ascii")
print(f"Desktop wallpaper: {image.width}x{image.height}, RGB565, {len(pixels)} bytes")
