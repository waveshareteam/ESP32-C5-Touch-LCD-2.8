"""Generate antialiased ARGB8888 weather artwork; requires Pillow."""
from pathlib import Path
from math import cos, sin, pi
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent
SCALE = 4
WIDTH, HEIGHT = 112, 96


def artwork(kind):
    image = Image.new("RGBA", (WIDTH * SCALE, HEIGHT * SCALE))
    draw = ImageDraw.Draw(image)

    def bounds(values):
        return tuple(round(value * SCALE) for value in values)

    def ellipse(values, color):
        draw.ellipse(bounds(values), fill=color)

    def line(points, color, width=3):
        points = [(round(x * SCALE), round(y * SCALE)) for x, y in points]
        draw.line(points, fill=color, width=round(width * SCALE))
        for x, y in points:
            r = width * SCALE / 2
            draw.ellipse((x-r, y-r, x+r, y+r), fill=color)

    def sun(cx, cy, radius):
        for index in range(8):
            angle = pi * index / 4
            line([(cx + cos(angle) * (radius + 6), cy + sin(angle) * (radius + 6)),
                  (cx + cos(angle) * (radius + 12), cy + sin(angle) * (radius + 12))], "#edb449", 3)
        ellipse((cx-radius, cy-radius, cx+radius, cy+radius), "#f2be50")
        ellipse((cx-radius+4, cy-radius+3, cx+radius-4, cy+radius-5), "#f8cc6d")

    def cloud(y=18, dark=False):
        color = "#9cb3ae" if dark else "#c2d6cf"
        ellipse((14, y+24, 53, y+58), color)
        ellipse((29, y+6, 77, y+55), color)
        ellipse((59, y+20, 99, y+58), color)
        draw.rounded_rectangle(bounds((28, y+30, 83, y+58)), radius=10*SCALE, fill=color)
        if not dark:
            ellipse((31, y+9, 72, y+49), "#d5e4dc")
            draw.rounded_rectangle(bounds((22, y+32, 91, y+54)), radius=10*SCALE, fill="#d5e4dc")

    if kind == "sunny":
        sun(56, 45, 22)
    elif kind == "cloudy":
        sun(77, 30, 16)
        cloud(20)
    elif kind in ("overcast", "unknown"):
        cloud(9)
        if kind == "unknown":
            for x in (43, 56, 69):
                ellipse((x-2, 78, x+2, 82), "#6a9483")
    elif kind in ("rain", "thunder"):
        cloud(1, dark=True)
        if kind == "rain":
            for x in (32, 55, 78):
                line([(x, 73), (x-5, 84)], "#399d9b", 4)
        else:
            draw.polygon([tuple(bounds(p)) for p in ((57, 61), (45, 78), (56, 78),
                                                       (49, 93), (72, 70), (60, 70), (66, 61))], fill="#e2ad38")
    elif kind == "snow":
        cloud(1)
        for x in (32, 56, 80):
            for a in (0, pi/3, 2*pi/3):
                line([(x-cos(a)*5, 79-sin(a)*5), (x+cos(a)*5, 79+sin(a)*5)], "#6eaba9", 2)
    elif kind == "fog":
        cloud(1)
        for y, left, right in ((69, 24, 88), (80, 34, 78)):
            line([(left, y), (right, y)], "#9ab4a9", 4)
    return image.resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS)


def main():
    names = ("unknown", "sunny", "cloudy", "overcast", "rain", "thunder", "snow", "fog")
    output = ['/* Generated by generate_weather_icons.py. */', '#include "weather_icons.h"', '']
    sheet = Image.new("RGB", (WIDTH * 4, HEIGHT * 2), "#f6faf8")
    for index, name in enumerate(names):
        image = artwork(name)
        image.save(ROOT / f"weather_{name}.png")
        sheet.paste(image, ((index % 4)*WIDTH, (index // 4)*HEIGHT), image)
        pixels = image.tobytes("raw", "BGRA")
        output.append(f"static const LV_ATTRIBUTE_MEM_ALIGN uint8_t pixels_{name}[] = {{")
        for offset in range(0, len(pixels), 32):
            output.append("    " + ",".join(f"0x{byte:02x}" for byte in pixels[offset:offset+32]) + ",")
        output.extend(["};", ""])
    output.append("const lv_image_dsc_t weather_icons[WEATHER_ICON_COUNT] = {")
    for name in names:
        output.extend(["    {", "        .header = { .magic = LV_IMAGE_HEADER_MAGIC,",
                       f"                    .cf = LV_COLOR_FORMAT_ARGB8888, .w = {WIDTH}, .h = {HEIGHT}, .stride = {WIDTH * 4} }},",
                       f"        .data_size = sizeof(pixels_{name}), .data = pixels_{name},", "    },"])
    output.append("};")
    (ROOT / "weather_icons.c").write_text("\n".join(output) + "\n", encoding="ascii")
    sheet.save(ROOT / "weather_icons_preview.png")


if __name__ == "__main__":
    main()
