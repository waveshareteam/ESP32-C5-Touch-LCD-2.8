"""Convert the supplied Sensor icon to an LVGL 9 ARGB8888 C asset (Pillow)."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent
image = Image.open(ROOT / "sensor_icon_source.png").convert("RGBA")
image = image.resize((112, 112), Image.Resampling.LANCZOS)
pixels = image.tobytes("raw", "BGRA")  # ESP32 little-endian ARGB8888
lines = ['/* Generated by generate_sensor_icon.py. */', '#include "lvgl.h"', '',
         'static const LV_ATTRIBUTE_MEM_ALIGN uint8_t sensor_icon_pixels[] = {']
for offset in range(0, len(pixels), 32):
    lines.append("    " + ",".join(f"0x{value:02x}" for value in pixels[offset:offset + 32]) + ",")
lines += ['};', '', 'const lv_image_dsc_t img_app_sensor = {',
          '    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888,',
          '                .w = 112, .h = 112, .stride = 112 * 4 },',
          '    .data_size = sizeof(sensor_icon_pixels), .data = sensor_icon_pixels,',
          '};', '']
(ROOT / "img_app_sensor.c").write_text("\n".join(lines), encoding="ascii")
print(f"Sensor icon: {image.width}x{image.height}, ARGB8888, {len(pixels)} bytes")
